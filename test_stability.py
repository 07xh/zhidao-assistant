from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent
PAYLOAD = ROOT / 'payload'

def read(name: str) -> str:
    return (PAYLOAD / name).read_text(encoding='utf-8-sig')

# The GUI writes this consent marker and the command shim enforces the same one.
gui = read('Zhidao-GUI.ps1')
task = read('Zhidao-Task.cmd')
privacy = read('隐私政策与数据说明.txt')
markers = set(re.findall(r'privacy-accepted-[A-Za-z0-9.-]+\.flag', gui + task + privacy))
assert markers == {'privacy-accepted-v5.2.7.flag'}, markers
assert "'V5.2.7 accepted at '" in gui

# Ensure the GUI invokes the selected primary video controller, not an arbitrary first <video>.
player = read('Official-Player.ps1')
assert 'c.playPrimaryFromUserGesture()' in player
assert 'c.applyRate()' in player
assert 'document.querySelectorAll("video")' not in player

# Version metadata and package manifest must agree.
installer = read('Install.ps1')
assert "DisplayVersion -Value '5.2.8'" in installer
assert 'Zhidao Assistant V5.2.8' in installer
assert installer.count('& $uv venv --python $pythonSource $venv') == 1
build = (ROOT / 'build.py').read_text(encoding='utf-8')
assert 'ZhidaoAssistant-Setup-v5.2.8-hotfix9-zhs-reliability.exe' in build

go_installer = (ROOT / 'src' / 'installer.go').read_text(encoding='utf-8')
assert 'V5.2.8' in go_installer

# Window version and cache/session integration must agree.
assert 'V5.2.8' in read('Zhidao-UI.xaml')
assert 'Get-SessionFingerprint' in gui and 'sessionFingerprint -ceq $currentFingerprint' in gui
assert 'if (Launch-Verify $true $target)' in gui
assert 'Load-PendingVerify' in gui and 'Check-VerifyExit' in gui
assert 'Get-FileHash -LiteralPath (Join-Path $stageDir $name)' in installer
assert 'AppLifecycle.ps1' in installer
assert 'AppLifecycle.ps1' in read('Uninstall.ps1')
assert 'RemoveZhsData' in read('Uninstall.ps1') and 'cannot delete the shared .zhs folder' in read('Uninstall.ps1')

# Both WPF documents remain well-formed XML.
for name in ('Zhidao-UI.xaml', 'Consent-UI.xaml'):
    ET.parse(PAYLOAD / name)

# Required install payload files must be present.
for name in (
    'Zhidao-GUI.ps1', 'Zhidao-UI.xaml', 'Consent-UI.xaml',
    'Zhidao-Task.cmd', 'zhidao_only.py', 'Official-Player.ps1',
    'Official-MediaController.js', 'Install-WebView2.ps1', 'Uninstall.ps1', 'AppLifecycle.ps1',
    '使用条款与第三方声明.txt', '隐私政策与数据说明.txt', 'LICENSE-GPL-3.0.txt'
):
    assert (PAYLOAD / name).is_file(), name

print('Passed stability checks:')
print('1. GUI/task/privacy consent marker is identical')
print('2. Manual playback and speed actions target the primary controller')
print('3. Installer/app/build version metadata agrees on 5.2.8')
print('4. Python venv creation is not duplicated')
print('5. WPF XAML documents parse')
print('6. Required installation payload is complete (launcher generated by build.py)')

print('7. GUI cache mismatch protection, pending verify and installer staging present')
